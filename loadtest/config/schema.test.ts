// Unit tests for the unified loadtest.config.json schema (loadtest/DESIGN.md
// §2). Every negative test asserts on the named error code from DESIGN
// §2.1's cross-field validation table so a code can never silently drift
// from its test. Uses a FIXTURE copy of summary.json via deriveDevnet's
// override options — never the live tests/devnet/summary.json.
